"""Evaluate the baseline and the ML model on SYNTHETIC data and write a report.

    cd ml && .venv/bin/python -m mapchat_floor.evaluate --out ../docs/EVALUATION.md

Train and test sets come from different random seeds, so the test sessions
use buildings, weather drift and walking patterns the model never saw.
Metrics are computed on indoor samples only.
"""
from __future__ import annotations

import argparse
from datetime import date

import numpy as np
import pandas as pd

from . import baseline
from .model import FloorModel
from .synth import generate


def accuracy(pred: np.ndarray, truth: np.ndarray) -> tuple[float, float]:
    d = np.abs(np.asarray(pred) - np.asarray(truth))
    return float(np.mean(d == 0)), float(np.mean(d <= 1))


def run(train_sessions: int = 240, test_sessions: int = 120, seed: int = 1) -> dict:
    train = generate(train_sessions, seed=seed)
    test = generate(test_sessions, seed=seed + 1000)

    model = FloorModel(seed=seed).fit(train[train["indoor"]])

    t = test[test["indoor"]].copy()
    t["baseline"] = baseline.estimate(test).loc[t.index].to_numpy()
    t["model"] = model.predict(test).astype(int)[test["indoor"].to_numpy()]
    t["t_min"] = (t["t_s"] - t["entry_index"]) / 60.0

    rows = []

    def add(name: str, mask: pd.Series) -> None:
        sub = t[mask]
        if len(sub) == 0:
            return
        be, b1 = accuracy(sub["baseline"], sub["true_floor"])
        me, m1 = accuracy(sub["model"], sub["true_floor"])
        rows.append((name, len(sub), be, b1, me, m1))

    add("All indoor samples", t["indoor"])
    add("Settled (idle on a floor)", t["movement"] == "idle")
    add("Moving: stairs", t["movement"] == "stairs")
    add("Moving/waiting: elevator", t["movement"] == "elevator")
    add("First 5 min after entry", t["t_min"] < 5)
    add("More than 5 min after entry", t["t_min"] >= 5)
    add("Tall buildings (7+ floors)", t["n_floors"] >= 7)

    return {
        "rows": rows,
        "n_train_sessions": train_sessions,
        "n_test_sessions": test_sessions,
        "n_train_samples": int(train["indoor"].sum()),
        "n_test_samples": int(len(t)),
        "seed": seed,
    }


def report(res: dict) -> str:
    pct = lambda x: f"{100 * x:.1f}%"  # noqa: E731
    settled = next(r for r in res["rows"] if r[0].startswith("Settled"))
    late = next(r for r in res["rows"] if r[0].startswith("More than 5"))
    early = next(r for r in res["rows"] if r[0].startswith("First 5"))
    reading = (
        f"On this synthetic data, the ML model changes settled exact-floor accuracy from "
        f"{pct(settled[2])} (baseline) to {pct(settled[4])}. Both are about 100% within ±1 floor, which is "
        f"**probably optimistic**: the simulator's combined errors rarely exceed one floor. The baseline loses "
        f"accuracy over time ({pct(early[2])} in the first 5 min vs {pct(late[2])} later) because of weather drift, "
        f"which the ML model only partly corrects ({pct(early[4])} → {pct(late[4])})."
    )
    table = "\n".join(
        f"| {name} | {n:,} | {pct(be)} | {pct(b1)} | {pct(me)} | {pct(m1)} |" for name, n, be, b1, me, m1 in res["rows"]
    )
    return f"""# Floor estimation — evaluation

> ⚠️ **All numbers below come from SYNTHETIC data** generated by
> `ml/mapchat_floor/synth.py`. They measure the pipeline against our own
> simulation assumptions, **not** real-world accuracy. Real numbers will come
> from consented logging (`public.floor_samples`, Phase 7) and will replace
> this table.

Generated {date.today().isoformat()} by `python -m mapchat_floor.evaluate`
(seed {res['seed']}). Train: {res['n_train_sessions']} sessions
({res['n_train_samples']:,} indoor samples at 1 Hz). Test:
{res['n_test_sessions']} **different** sessions ({res['n_test_samples']:,}
samples), with new buildings, weather drift and walks.

## Methods

- **Baseline (rule-based):** `floor = 1 + round(Δh / nominal floor height)`,
  where Δh is the height change since entering the building, computed from
  pressure (median of the first 5 s indoors as the reference). Clamped to the
  building's floor count.
- **ML model:** a random-forest regressor on causal features: raw Δh, 15 s and
  60 s rolling medians (spike suppression), 10 s vertical speed, minutes since
  entry (drift), nominal floor height and floor count. The prediction is
  rounded and clamped.

## Results

| Subset | Samples | Baseline exact | Baseline ±1 | ML exact | ML ±1 |
|---|---:|---:|---:|---:|---:|
{table}

**Reading the results.** {reading}

"Exact" means the estimated floor equals the true floor. "±1" means it is
off by at most one floor. During stairs and elevator movement the truth is
the nearest floor to the person's current height, which is ambiguous
mid-flight, so the **settled** row is the one that matters most for the app.

## What the simulation includes (assumptions)

Weather drift of about 60 Pa/h (sd), sensor noise of 2.5 Pa, building
pressurization of +2–10 Pa, door spikes of ±10–30 Pa, stairwell offsets of
±3–12 Pa, a tall lobby (1.0–1.4× the floor height) plus ±0.2 m jitter per
floor, stairs at 0.25–0.40 m/s, and elevators at 1–2 m/s after a 10–45 s wait.
The app only knows the building's **nominal** floor height.

## Limitations

- Synthetic data: the error sources and their sizes are guesses. Real
  stairwells, HVAC, phones in pockets and temperature changes will differ.
- The model is trained on dense ground truth. Real logging gives only sparse
  "I'm on floor N" confirmations, so real training will need
  interpolation between confirmations, or semi-supervised labels.
- The entry floor is assumed to be floor 1. Buildings on slopes (common at
  UNC) have entrances on several floors, so per-entrance floor labels from the
  indoor maps are needed.

## Next improvements

1. Log real data with consent (iOS logging mode → `floor_samples`, CSV
   export) in the 10 mapped buildings, with confirmed floors.
2. Per-building calibration: learn the real floor heights and lobby height
   from confirmed floors, replacing nominal heights.
3. Re-zero on known events: a confirmed floor, an elevator ride's end (sharp
   vertical-speed stop), or `CLLocation.floor` when Apple provides it, to
   cancel weather drift.
4. Use the entrance's floor (from the indoor map) as the reference floor
   instead of assuming floor 1.
5. A small state machine/HMM over floors (people are on a floor most of the
   time and change floors in discrete jumps) on top of either estimator.
"""


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="../docs/EVALUATION.md")
    ap.add_argument("--train", type=int, default=240)
    ap.add_argument("--test", type=int, default=120)
    args = ap.parse_args()
    res = run(args.train, args.test)
    with open(args.out, "w") as f:
        f.write(report(res))
    for r in res["rows"]:
        print(f"{r[0]:32} n={r[1]:6}  baseline {r[2]:.3f}/{r[3]:.3f}  ml {r[4]:.3f}/{r[5]:.3f}")
    print(f"wrote {args.out}")
